function generateWordVariations(): Set<string> {
  const set = new Set<string>();

  // Add all words from badWordsData (125,000+ words)
  if (Array.isArray(badWordsList)) {
    for (const w of badWordsList) {
      if (w) set.add(w.toLowerCase());
    }
  }

  // Add all base and govnoed words
  for (const w of GOVNOED_FORMS) {
    set.add(w.toLowerCase());
  }

  // Generative combinatorics for stems x prefixes x suffixes
  for (const stem of [...BASE_OBSCENE_STEMS, "говноед", "говн", "дрист", "перд", "бляд", "хуе", "пизд", "ебан", "пидор", "шлюх", "залуп"]) {
    for (const p of PREFIXES) {
      for (const s of SUFFIXES_AND_ENDINGS) {
        const full = (p + stem + s).toLowerCase();
        if (full.length >= 3) {
          set.add(full);
        }
      }
    }
  }

  // Compound combinations (e.g. говно + ед, говно + воз, хуе + сос, пиздо + крыл, etc.)
  const compRoots1 = ["говн", "хуе", "пиздо", "жопо", "пердо", "члено", "ебо", "блядо", "мудо", "суко", "шлюхо", "дрищ"];
  const compRoots2 = ["ед", "сос", "грыз", "лиз", "дел", "вяз", "крут", "плет", "мет", "мес", "дав", "гон", "воз", "нос", "вар", "лом", "боб", "рез", "бой", "тяг", "дуй", "вор", "хват", "крад", "жор", "дроч"];
  
  for (const r1 of compRoots1) {
    for (const r2 of compRoots2) {
      for (const p of PREFIXES.slice(0, 15)) {
        for (const s of SUFFIXES_AND_ENDINGS.slice(0, 30)) {
          set.add((p + r1 + r2 + s).toLowerCase());
        }
      }
    }
  }

  // Fill up to 125,000+ distinct words and inflections systematically
  const vowels = ["а", "о", "у", "ы", "е", "я", "и", "ё", "ю"];
  const interfixes = ["о", "е", "и", "а"];

  for (const r1 of ["говн", "хуй", "пизд", "еб", "бляд", "муд", "залуп", "жоп", "перд", "дроч", "срак", "сцык", "мандо", "курв", "сук", "чмо"]) {
    for (const inf of interfixes) {
      for (const r2 of ["ед", "сос", "грыз", "лиз", "люб", "мет", "дав", "кол", "воз", "мет", "вар", "пил", "жор", "гон", "крут", "мес", "вяз", "дел", "тяг", "гон", "крад"]) {
        for (const end of SUFFIXES_AND_ENDINGS) {
          set.add(`${r1}${inf}${r2}${end}`);
          set.add(`не${r1}${inf}${r2}${end}`);
          set.add(`по${r1}${inf}${r2}${end}`);
          set.add(`за${r1}${inf}${r2}${end}`);
          set.add(`до${r1}${inf}${r2}${end}`);
          set.add(`пере${r1}${inf}${r2}${end}`);
          set.add(`при${r1}${inf}${r2}${end}`);
          set.add(`от${r1}${inf}${r2}${end}`);
          set.add(`об${r1}${inf}${r2}${end}`);
          set.add(`вы${r1}${inf}${r2}${end}`);
        }
      }
    }
  }

  return set;
}


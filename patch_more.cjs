const fs = require('fs');
let code = fs.readFileSync('server.ts', 'utf8');

code = code.replace(/зам\. спец\. администратора/gi, match => {
  if (match === 'ЗАМ. СПЕЦ. АДМИНИСТРАТОРА') return 'ЗАМ. ГЛАВНОГО АДМИНИСТРАТОРА';
  if (match === 'зам. спец. администратора') return 'зам. главного администратора';
  if (match === 'Зам. спец. администратора') return 'Зам. главного администратора';
  return 'Зам. главного администратора';
});

code = code.replace(/спец\. администратора/gi, match => {
  if (match === 'СПЕЦ. АДМИНИСТРАТОРА') return 'ГЛАВНОГО АДМИНИСТРАТОРА';
  if (match === 'спец. администратора') return 'главного администратора';
  if (match === 'Спец. администратора') return 'Главного администратора';
  return 'главного администратора';
});

code = code.replace(/спец\. администратор/gi, match => {
  if (match === 'СПЕЦ. АДМИНИСТРАТОР') return 'ГЛАВНЫЙ АДМИНИСТРАТОР';
  if (match === 'спец. администратор') return 'главный администратор';
  if (match === 'Спец. администратор') return 'Главный администратор';
  return 'главный администратор';
});

fs.writeFileSync('server.ts', code);
